"""
embedding_result.py

Domain model representing an embedding generated for a document chunk.
"""

from pydantic import BaseModel, Field


class EmbeddingResult(BaseModel):
    """
    Represents the embedding generated for a document chunk.

    Attributes
    ----------
    chunk_id
        Identifier of the source document chunk.

    vector
        Numerical representation of the chunk generated by
        the embedding model.

    model_name
        Name of the embedding model used to generate the vector.

    dimensions
        Number of dimensions in the generated vector.
    """

    chunk_id: str = Field(
        description="Identifier of the source document chunk.",
    )

    vector: list[float] = Field(
        description="Embedding vector generated for the chunk.",
    )

    model_name: str = Field(
        description="Name of the embedding model used.",
    )

    dimensions: int = Field(
        gt=0,
        description="Number of dimensions in the embedding vector.",
    )